package com.prism.music

import com.prism.music.data.model.AlbumItem
import com.prism.music.data.model.PlaylistItem
import com.prism.music.data.model.Shelf
import com.prism.music.data.model.Song
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.LocalDate

class VelouraPlaylistsTest {
    private fun pl(id: String, title: String = id, mix: Boolean = false) = PlaylistItem(id, title, "YouTube Music", null, isMix = mix)

    @Test
    fun autoGeneratedMixesAreRecognisedButEditorialPlaylistsAreNot() {
        assertTrue(VelouraPlaylists.isMix(pl("RDTMAK5uy_supermix")))
        assertTrue(VelouraPlaylists.isMix(pl("VLRDTMAK5uy_discover")))
        assertTrue(VelouraPlaylists.isMix(pl("anything", mix = true)))
        assertFalse(VelouraPlaylists.isMix(pl("RDCLAK5uy_chill")))
        assertFalse(VelouraPlaylists.isMix(pl("PLmyOwnPlaylist")))
    }

    @Test
    fun accountPlaylistsLeaveOutLikedMusicAndDuplicates() {
        val library = listOf(pl("VLLM", "Liked Music"), pl("VLPLa"), pl("PLa"), pl("PLb"), AlbumItem("MPREb_x", "An album", "", null))
        assertEquals(listOf("VLPLa", "PLb"), VelouraPlaylists.accountPlaylists(library).map { it.id })
    }

    @Test
    fun suggestionsSkipWhatIsAlreadySavedAndPutMixesFirst() {
        val shelves = listOf(
            Shelf("Recommended", items = listOf(pl("RDCLAK5uy_chill"), pl("PLsaved"))),
            Shelf("Mixed for you", items = listOf(pl("RDTMAK5uy_supermix", "My Supermix", mix = true), pl("RDTMAK5uy_supermix"))),
            Shelf("Liked", items = listOf(pl("LM"))),
        )
        val library = listOf(pl("VLPLsaved"))
        assertEquals(listOf("RDTMAK5uy_supermix", "RDCLAK5uy_chill"), VelouraPlaylists.suggestions(shelves, library).map { it.id })
    }

    @Test
    fun aSavedMixCopyIsNamedAfterTheMixAndTheDay() {
        assertEquals("My Supermix · 8 Nov 2026", VelouraPlaylists.copyTitle("My Supermix", LocalDate.of(2026, 11, 8)))
    }

    @Test
    fun onlyPlayableSongsGoIntoASavedCopyEachOnce() {
        val songs = listOf(
            Song("a", "A"), Song("b", "B"), Song("a", "A again"),
            Song("ep", "An episode", isEpisode = true), Song("live", "A stream", isLive = true), Song("", "No id"),
        )
        assertEquals(listOf("a", "b"), VelouraPlaylists.saveableIds(songs))
    }
}
